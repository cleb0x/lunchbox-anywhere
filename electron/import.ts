const list = (dir: string) => readdir(dir, { withFileTypes: true }).catch(() => [])

type Candidate = { agent: ChatSource; file: string; at: number; size: number }
async function candidates(home: string): Promise<Candidate[]> {
  const r = roots(home)
  const out: Candidate[] = []
  const add = async (agent: ChatSource, file: string) => {
    const s = await stat(file).catch(() => null)
    if (s?.isFile() && s.size > 0) out.push({ agent, file, at: s.mtimeMs, size: s.size })
  }
  await Promise.all([
    (async () => {
      for (const d of await list(r.claude)) if (d.isDirectory()) for (const f of await list(join(r.claude, d.name))) if (f.isFile() && f.name.endsWith('.jsonl')) await add('claude', join(r.claude, d.name, f.name))
    })(),
    (async () => {
      for (const y of await list(r.codex)) if (y.isDirectory()) for (const m of await list(join(r.codex, y.name))) if (m.isDirectory()) for (const d of await list(join(r.codex, y.name, m.name))) if (d.isDirectory()) {
        const dir = join(r.codex, y.name, m.name, d.name)
        for (const f of await list(dir)) if (f.isFile() && /^rollout-.*\.jsonl$/.test(f.name)) await add('codex', join(dir, f.name))
      }
    })(),
    (async () => {
      for (const d of await list(r.gemini)) if (d.isDirectory()) {
        for (const f of await list(join(r.gemini, d.name, 'chats'))) if (f.isFile() && /\.jsonl?$/.test(f.name)) await add('gemini', join(r.gemini, d.name, 'chats', f.name))
        for (const f of await list(join(r.gemini, d.name))) if (f.isFile() && /^checkpoint-.*\.json$/.test(f.name)) await add('gemini', join(r.gemini, d.name, f.name))
      }
    })(),
    (async () => {
      for (const d of await list(r.grok)) if (d.isDirectory()) for (const s of await list(join(r.grok, d.name))) if (s.isDirectory()) await add('grok', join(r.grok, d.name, s.name, 'chat_history.jsonl'))
    })(),
  ])
  return out.sort((a, b) => b.at - a.at)
}

// Where a Gemini chat was held. Newer versions write the folder beside the chats; older ones
// name the folder by a hash, which the projects list maps back.
function geminiFolder(file: string, home: string) {
  const dir = basename(dirname(file)) === 'chats' ? dirname(dirname(file)) : dirname(file)
  try { return readFileSync(join(dir, '.project_root'), 'utf8').trim() } catch {}
  try {
    const projects = JSON.parse(readFileSync(join(home, '.gemini', 'projects.json'), 'utf8')).projects ?? {}
    return Object.entries(projects).find(([, name]) => name === basename(dir))?.[0] ?? ''
  } catch { return '' }
}

const grokMeta = (file: string) => {
  const summary = json(((): string => { try { return readFileSync(join(dirname(file), 'summary.json'), 'utf8') } catch { return '' } })())
  const info = (summary.info ?? {}) as { id?: string; cwd?: string }
  let folder = typeof info.cwd === 'string' ? info.cwd : ''
  if (!folder) try { folder = decodeURIComponent(basename(dirname(dirname(file)))) } catch {}
  return { id: String(info.id ?? basename(dirname(file))), folder, title: String(summary.generated_title ?? ''), from: when(summary.created_at), to: when(summary.updated_at) }
}

const codexTitles = (home: string) => {
  const titles = new Map<string, string>()
  try {
    for (const line of linesOf(readFileSync(join(home, '.codex', 'session_index.jsonl'), 'utf8'))) {
      const o = parse(line)
      if (o?.id && typeof o.thread_name === 'string') titles.set(o.id, o.thread_name)
    }
  } catch {}
  return titles
}

const HEAD = 3e6
const one = (s: string, n = 180) => s.replace(/\s+/g, ' ').trim().slice(0, n)

// Enough of a session to list it: whose it is, where it was held and how it began. Only the
// start of the file is read.
async function glance(c: Candidate, home: string, titles: Map<string, string>): Promise<FoundChat | null> {
  let chat: Body
  try {
    if (c.agent === 'gemini') {
      if (c.size > 40e6) return null
      chat = { ...geminiChat(await readFile(c.file, 'utf8')), folder: geminiFolder(c.file, home) }
    } else {
      // A cut that lands inside a line leaves one that does not parse, which is skipped.
      const r = readers[c.agent]()
      let seen = 0
      const started = () => { const t = r.done().turns; for (; seen < t.length; seen++) if (t[seen].you) return true; return false }
      chat = await feed(c.file, r, started, HEAD)
      if (c.agent === 'grok') chat = { ...chat, ...grokMeta(c.file) }
    }
  } catch { return null }
  const first = chat.turns.find((t) => t.you)?.text ?? ''
  if (!first) return null
  const id = chat.id || (c.agent === 'claude' ? basename(c.file, '.jsonl') : c.agent === 'codex' ? basename(c.file).match(/([0-9a-f]{8}-[0-9a-f-]{27})\.jsonl$/)?.[1] ?? '' : basename(c.file).replace(/\.jsonl?$/, ''))
  const title = chat.title || (c.agent === 'codex' ? titles.get(id) ?? '' : '')
  return { agent: c.agent, id, file: c.file, folder: chat.folder, there: !!chat.folder && isFolder(chat.folder), first: one(first), title: one(title, 80) || undefined, at: c.at, size: c.size }
}

const isFolder = (path: string) => { try { return statSync(path).isDirectory() } catch { return false } }

// The newest sessions on this computer, across every agent that keeps them.
export async function found(home: string, limit = 150, skip: (id: string) => boolean = () => false): Promise<FoundChat[]> {
  const files = await candidates(home)
  const titles = codexTitles(home)
  const out: FoundChat[] = []
  // A few at a time: each glance opens a file, and there can be thousands.
  for (let i = 0; i < files.length && out.length < limit; i += 8) {
    const got = await Promise.all(files.slice(i, i + 8).map((c) => glance(c, home, titles)))
    for (const f of got) if (f && !skip(f.id) && out.length < limit) out.push(f)
  }
  return out
}

// A session file the renderer names is read only if it lies where sessions are kept.
export function allowed(file: string, agent: ChatSource, home: string) {
  const root = roots(home)[agent]
  const abs = resolve(file)
  return !!root && abs.startsWith(resolve(root) + sep) && /\.jsonl?$/.test(abs) && existsSync(abs)
}

export async function read(agent: ChatSource, file: string, home: string): Promise<Chat> {
  const base = basename(file)
  if (agent === 'gemini') {
    const c = geminiChat(await readFile(file, 'utf8'))
    return { agent, ...c, id: c.id || base.replace(/\.jsonl?$/, ''), folder: geminiFolder(file, home) }
  }
  const c = await feed(file, readers[agent]())
  if (agent === 'claude') return { agent, ...c, id: c.id || basename(file, '.jsonl') }
  if (agent === 'codex') {
    const id = c.id || base.match(/([0-9a-f]{8}-[0-9a-f-]{27})\.jsonl$/)?.[1] || ''
    return { agent, ...c, id, title: codexTitles(home).get(id) ?? '' }
  }
  const meta = grokMeta(file)
  // Grok does not date its messages, so they are spread over the time the session was open.
  const span = Math.max(0, meta.to - meta.from)
  c.turns.forEach((t, i) => { t.at = meta.from + (c.turns.length > 1 ? Math.round((span * i) / (c.turns.length - 1)) : 0) })
  return { agent, ...c, id: meta.id, folder: meta.folder, title: meta.title }
}

// How much of a chat a room carries. A session can run to thousands of turns; the room keeps the
// newest ones, starting on one of the person's messages, and says what it left out.
const MAX_TURNS = 400
const MAX_CHARS = 600_000
const MAX_TEXT = 40_000
const MAX_ACTS = 150

export function fit(turns: Turn[]): { kept: Turn[]; dropped: number } {
  let from = turns.length
  for (let size = 0; from > 0 && turns.length - from < MAX_TURNS; from--) {
    size += Math.min(turns[from - 1].text.length, MAX_TEXT)
    if (size > MAX_CHARS && from < turns.length) break
  }
  while (from > 0 && from < turns.length && !turns[from].you) from++
  if (from >= turns.length) from = Math.max(0, turns.length - 1)
  const kept = turns.slice(from).map((t) => ({
    ...t,
    text: t.text.length > MAX_TEXT ? `${t.text.slice(0, MAX_TEXT)}\n\n[The rest of this message was left out when the chat was imported.]` : t.text,
    acts: t.acts.slice(-MAX_ACTS),
  }))
  return { kept, dropped: from }
}

const day = (t: number) => new Date(t).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })
const uid = () => randomUUID().replace(/-/g, '').slice(0, 14)
const count = (n: number, word: string) => `${n.toLocaleString('en-US')} ${word}${n === 1 ? '' : 's'}`

// The room a chat becomes. `how` says which way the conversation carries on: resumed means the
// agent is handed its own session back, so it is not sent the conversation again.
export function room(chat: Chat, how: { resumed: boolean; folderGone: boolean; ready: boolean }, now = Date.now()) {
  const { kept, dropped } = fit(chat.turns)
  const name = NAMES[chat.agent]
  const dated = chat.turns.filter((t) => t.at > 0)
  const from = dated[0]?.at ?? now
  const to = dated.at(-1)?.at ?? now
  let at = 0
  const stamp = (t: number) => (at = Math.max(at + 1, t || 0))
  const events: Event[] = kept.filter((t) => t.you || t.text || t.acts.length).map((t) =>
    t.you ? { id: uid(), at: stamp(t.at), kind: 'you', text: t.text } : { id: uid(), at: stamp(t.at), kind: 'say', who: chat.agent, text: t.text, acts: t.acts })
  const span = day(from) === day(to) ? day(from) : `${day(from)} to ${day(to)}`
  const carries = how.resumed ? `${name} carries on in the same session, so it remembers all of it.`
    : how.folderGone ? `Its folder is no longer there, so this room has a folder of its own and the agents read the conversation from here.`
      : !how.ready ? `${name} is not set up in Lunchbox, so the agents here read the conversation instead.`
        : `${name} cannot pick an old session up again, so it reads the conversation from here.`
  const left = dropped ? ` The first ${count(dropped, 'message')} are not shown${how.resumed ? `; ${name} still has them` : ''}.` : ''
  events.unshift({ id: uid(), at: (events[0]?.at ?? now) - 1, kind: 'note', text: `Brought in from ${name}: ${count(chat.turns.length, 'message')}, ${span}.${left} ${carries}` })
  // The arc of the chat in a few lines, for an agent that joins later or reads without the session.
  const asked = chat.turns.filter((t) => t.you).map((t) => `- ${one(t.text, 160)}`)
  const shown = asked.length > 28 ? [...asked.slice(0, 6), `- (${asked.length - 26} more)`, ...asked.slice(-20)] : asked
  const about = `This room continues a chat the person had in ${name}${chat.folder ? `, in ${chat.folder}` : ''}, ${span}. The conversation is in the room. What the person asked for, oldest first:\n${shown.join('\n')}`.slice(0, 5800)
  const title = one(chat.title || chat.turns.find((t) => t.you)?.text || `${name} chat`, 60)
  return { name: title, events, about }
}

export const resumes = (agent: ChatSource) => RESUMES.includes(agent)
