// Chats held in the agents' own apps, read from the files each one keeps on this computer and
// turned into a room. Nothing here writes to those files.

type Turn = { you: boolean; at: number; text: string; acts: Act[] }
type Body = { id: string; folder: string; title: string; turns: Turn[] }
export type Chat = Body & { agent: ChatSource }
// A session can be tens of megabytes, so it is read a line at a time and only the turns are kept.
type Reader = { line(l: string): void; done(): Body }
const all = (r: Reader, lines: Iterable<string>) => { for (const l of lines) r.line(l); return r.done() }

