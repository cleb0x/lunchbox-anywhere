// A line that is not JSON, the half-written last line of a session still in use, is skipped.
const parse = (line: string): any => { try { return line.length > 1 ? JSON.parse(line) : null } catch { return null } }
const when = (t: unknown, fallback = 0) => { const n = typeof t === 'number' ? t : Date.parse(String(t ?? '')); return Number.isFinite(n) ? n : fallback }
const texts = (content: unknown, kinds = ['text', 'input_text', 'output_text', 'Text']): string =>
  typeof content === 'string' ? content
    : Array.isArray(content) ? content.map((c) => (typeof c === 'string' ? c : c && typeof c.text === 'string' && (!c.type || kinds.includes(c.type)) ? c.text : '')).filter(Boolean).join('\n\n')
      : ''
const json = (s: unknown): Record<string, unknown> => { try { const o = typeof s === 'string' ? JSON.parse(s) : s; return o && typeof o === 'object' ? o as Record<string, unknown> : {} } catch { return {} } }

// What the tools around a chat put into the person's messages: reminders, the wrapping of a
// slash command, the opened file an editor reports. A slash command is kept as what was typed.
const WRAPPED = /<(system-reminder|ide_opened_file|ide_selection|local-command-stdout|local-command-stderr|local-command-caveat|command-message|user-prompt-submit-hook|environment_context|user_instructions|permissions instructions|turn_aborted|task-notification|subagent_notification|INSTRUCTIONS)>[\s\S]*?<\/\1>/g
export function person(raw: string): string {
  const slash = raw.match(/<command-name>\s*(\/[^<\s]*)\s*<\/command-name>/)
  if (slash) {
    const args = raw.match(/<command-args>([\s\S]*?)<\/command-args>/)?.[1]?.trim() ?? ''
    // /clear, /model and the like change the tool, not the conversation.
    return args ? `${slash[1]} ${args}` : ''
  }
  const text = raw.replace(WRAPPED, '').trim()
  if (/^\[Request interrupted by user/.test(text) || /^Caveat: The messages below were generated by the user while running local commands/.test(text)) return ''
  // Written by Codex for itself, in the person's name.
  if (/^# AGENTS\.md instructions/.test(text)) return ''
  return clean(text)
}

// Turns are built as the records go by: the person's message opens one, and everything the agent
// writes and does until the next message is its answer.
function builder() {
  const turns: Turn[] = []
  const calls = new Map<string, Act>()
  const agent = (at: number) => {
    const last = turns.at(-1)
    if (last && !last.you) return last
    const t: Turn = { you: false, at, text: '', acts: [] }
    turns.push(t)
    return t
  }
  return {
    turns,
    you(text: string, at: number) { if (text) turns.push({ you: true, at, text, acts: [] }) },
    say(text: string, at: number) { const said = clean(text).trim(); if (said) { const t = agent(at); t.text = t.text ? `${t.text}\n\n${said}` : said } },
    act(a: Act, at: number, id?: string) {
      if (a.t === 'cmd') { a.command = a.command.slice(0, 600); delete a.out }
      agent(at).acts.push(a)
      if (id) calls.set(id, a)
    },
    // A tool result only says how the call it answers went.
    failed(id: string) {
      const a = calls.get(id)
      if (a?.t === 'cmd' && !a.exit) a.exit = 1
      else if (a?.t === 'tool') a.ok = false
    },
  }
}

export function claudeReader(): Reader {
  const b = builder()
  let id = '', folder = '', title = ''
  const line = (l: string) => {
    // Most of a session file is requests, snapshots and attachments, some of them megabytes long.
    if (!/"type":\s*"(user|assistant|summary|custom-title|ai-title)"/.test(l)) return
    const o = parse(l)
    if (!o) return
    if (o.type === 'summary' && typeof o.summary === 'string') title ||= o.summary
    if (typeof o.customTitle === 'string') title = o.customTitle
    else if (typeof o.aiTitle === 'string') title ||= o.aiTitle
    // A subagent's own conversation, and records the tool wrote for itself.
    if (o.isSidechain || o.isMeta || o.isCompactSummary || !o.message) return
    id ||= typeof o.sessionId === 'string' ? o.sessionId : ''
    folder ||= typeof o.cwd === 'string' ? o.cwd : ''
    const at = when(o.timestamp)
    const content = o.message.content
    if (o.type === 'user') {
      for (const c of Array.isArray(content) ? content : []) if (c?.type === 'tool_result' && c.is_error && typeof c.tool_use_id === 'string') b.failed(c.tool_use_id)
      b.you(person(texts(content, ['text'])), at)
    } else if (o.type === 'assistant' && o.message.model !== '<synthetic>') {
      if (typeof content === 'string') b.say(content, at)
      for (const c of Array.isArray(content) ? content : []) {
        if (c?.type === 'text' && typeof c.text === 'string') b.say(c.text, at)
        if (c?.type === 'tool_use' && typeof c.name === 'string') b.act(toAct(c.name, json(c.input), '', false), at, c.id)
      }
    }
  }
  return { line, done: () => ({ id, folder, title, turns: b.turns }) }
}
export const claudeChat = (lines: Iterable<string>) => all(claudeReader(), lines)

// Codex wraps a command in the shell it ran it with.
const command = (c: unknown): string => {
  const parts = Array.isArray(c) ? c.map(String) : [String(c ?? '')]
  return parts.length === 3 && /^-l?c$/.test(parts[1]) ? parts[2] : parts.join(' ')
}
const patched = (patch: string): Act[] => [...patch.matchAll(/^\*\*\* (Add|Update|Delete) File: (.+)$/gm)].map((m) => ({ t: 'edit', path: m[2].trim(), change: m[1] === 'Add' ? 'write' : m[1].toLowerCase() }))

export function codexReader(): Reader {
  const b = builder()
  // Newer versions log each command and file change as it completes, with its exit code. Older
  // ones only log the raw tool call. Where both are present the completed items are the record.
  const rough: { turn: Turn; act: Act }[] = []
  let done = false
  let id = '', folder = ''
  const line = (l: string) => {
    const head = l.slice(0, 400)
    // Reasoning is sealed and token counts are bookkeeping; together they are most of a rollout.
    if (!/"type":\s*"(session_meta|response_item|event_msg)"/.test(head) || /"type":\s*"(reasoning|token_count)"/.test(head)) return
    const o = parse(l)
    const p = o?.payload
    if (!p) return
    const at = when(o.timestamp)
    if (o.type === 'session_meta') { id ||= String(p.id ?? p.session_id ?? ''); folder ||= typeof p.cwd === 'string' ? p.cwd : '' }
    else if (o.type === 'response_item') {
      if (p.type === 'message' && p.role === 'user') b.you(person(texts(p.content)), at)
      else if (p.type === 'message' && p.role === 'assistant') b.say(texts(p.content), at)
      else if (p.type === 'function_call' || p.type === 'local_shell_call' || p.type === 'custom_tool_call') {
        const name = String(p.name ?? 'shell')
        const input = p.type === 'local_shell_call' ? p.action ?? {} : p.type === 'custom_tool_call' ? { input: p.input } : json(p.arguments)
        const acts: Act[] = name === 'apply_patch' ? patched(String(input.input ?? input.patch ?? ''))
          : input.command !== undefined || input.cmd !== undefined ? [{ t: 'cmd', command: command(input.command ?? input.cmd), exit: null }]
            : [toAct(name, input, '', false)]
        for (const a of acts) { b.act(a, at); rough.push({ turn: b.turns.at(-1)!, act: a }) }
      }
    } else if (o.type === 'event_msg' && p.type === 'item_completed' && p.item) {
      const it = p.item
      if (it.type === 'CommandExecution') { done = true; b.act({ t: 'cmd', command: command(it.command), exit: typeof it.exit_code === 'number' ? it.exit_code : null }, at) }
      else if (it.type === 'FileChange') { done = true; for (const [path, c] of Object.entries(it.changes ?? {})) b.act({ t: 'edit', path, change: (c as { type?: string })?.type === 'add' ? 'write' : 'edit' }, at) }
      else if (it.type === 'WebSearch') b.act({ t: 'tool', name: 'web_search', detail: String(it.query ?? '').slice(0, 160), ok: true }, at)
    }
  }
  return {
    line,
    done: () => {
      if (done) for (const { turn, act } of rough.splice(0)) turn.acts.splice(turn.acts.indexOf(act), 1)
      return { id, folder, title: '', turns: b.turns.filter((t) => t.you || t.text || t.acts.length) }
    },
  }
}
