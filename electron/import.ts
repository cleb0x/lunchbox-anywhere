// Gemini CLI has kept a chat three ways over its versions: one JSON document with the messages,
// a JSONL log whose `$set` records replace them, and saved checkpoints of the API's own history.
export function geminiChat(text: string): Body {
  const b = builder()
  let id = ''
  let messages: any[] = []
  const whole = parse(text)
  if (Array.isArray(whole)) messages = whole
  else if (whole && Array.isArray(whole.messages)) { messages = whole.messages; id = String(whole.sessionId ?? '') }
  else {
    for (const line of text.split('\n')) {
      const o = parse(line)
      if (!o) continue
      if (typeof o.sessionId === 'string') id ||= o.sessionId
      if (Array.isArray(o.$set?.messages)) messages = [...o.$set.messages]
      else if (typeof o.type === 'string' && o.id) messages.push(o)
    }
  }
  for (const m of messages) {
    const at = when(m?.timestamp)
    // A checkpoint: the API's roles and parts.
    if (m?.role && Array.isArray(m.parts)) {
      const said = m.parts.map((p: any) => (typeof p?.text === 'string' && !p.thought ? p.text : '')).filter(Boolean).join('\n\n')
      if (m.role === 'user') b.you(person(said), at)
      else {
        b.say(said, at)
        for (const p of m.parts) if (p?.functionCall?.name) b.act(toAct(String(p.functionCall.name), json(p.functionCall.args), '', false), at)
      }
    } else if (m?.type === 'user') b.you(person(texts(m.content)), at)
    else if (m?.type === 'gemini') {
      b.say(texts(m.content), at)
      for (const c of Array.isArray(m.toolCalls) ? m.toolCalls : []) if (c?.name) b.act(toAct(String(c.name), json(c.args), '', c.status === 'error'), at)
    }
  }
  return { id, folder: '', title: '', turns: b.turns }
}

export function grokReader(): Reader {
  const b = builder()
  const line = (l: string) => {
    const o = parse(l)
    if (!o) return
    // Messages Grok adds on the person's behalf carry a reason; theirs do not.
    if (o.type === 'user' && !o.synthetic_reason) b.you(person(texts(o.content)), 0)
    else if (o.type === 'assistant') {
      b.say(texts(o.content), 0)
      for (const c of Array.isArray(o.tool_calls) ? o.tool_calls : []) if (c?.name) b.act(toAct(String(c.name), json(c.arguments), '', false), 0, c.id)
    } else if (o.type === 'backend_tool_call' && o.kind) {
      const k = o.kind
      b.act(toAct(String(k.name ?? k.action?.type ?? k.tool_type ?? 'search'), { query: k.action?.query ?? json(k.input).query }, '', false), 0)
    } else if (o.type === 'tool_result' && typeof o.tool_call_id === 'string' && /^(error|failed)\b/i.test(String(o.content ?? ''))) b.failed(o.tool_call_id)
  }
  return { line, done: () => ({ id: '', folder: '', title: '', turns: b.turns }) }
}
export const grokChat = (lines: Iterable<string>) => all(grokReader(), lines)

function* linesOf(text: string) {
  let from = 0
  while (from < text.length) {
    const to = text.indexOf('\n', from)
    yield text.slice(from, to < 0 ? text.length : to)
    if (to < 0) return
    from = to + 1
  }
}

// Feeds a file to a reader a line at a time. `until` ends it early, once enough is known to list
// the session, and `upTo` is where it gives up looking.
async function feed(file: string, r: Reader, until?: () => boolean, upTo?: number) {
  const input = createReadStream(file, upTo ? { end: upTo } : {})
  const rl = createInterface({ input, crlfDelay: Infinity })
  try {
    for await (const l of rl) {
      r.line(l)
      if (until?.()) break
    }
  } finally {
    rl.close()
    input.destroy()
  }
  return r.done()
}

